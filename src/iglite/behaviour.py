"""Behaviour analysis: learn what each device normally does and flag what changes.

Threat intelligence only knows what someone has already reported. Behaviour
analysis catches the rest: a smart plug that starts calling an unknown server
every ten seconds, a printer looking up random-looking domains, a NAS that
suddenly accepts SSH from the internet. It works from the connection database
(``conn_log`` / ``dns_log``) plus an hourly activity counter, so nothing extra
is collected.

Each device gets a **baseline** once it has been seen for ``behaviour_learn_days``
(7): the servers, domains and ports it uses, whether anything ever connects in,
the hours it is active and how busy a normal hour is. Then each scan checks:

==================  =========================================================  ========
kind                what                                                       baseline
==================  =========================================================  ========
beaconing           regular new connections to one server (malware check-ins)   no
dga                 lookups of random-looking domains (generated by malware)    no
new_inbound         the internet connects in on a port that never saw that      yes
new_port            a port/protocol the device never used (risky ports: high)   yes
new_destination     a server/site outside the habits of a narrow device (IoT)   yes
destination_burst   many never-seen destinations in one hour                   yes
odd_hour            activity in an hour of day the device is always quiet       yes
volume_spike        far more connections in an hour than ever before            yes
==================  =========================================================  ========

Common services (Google, Apple, CDNs...; see common.py) never count as new
destinations or beacons. Findings are stored as **anomalies**, one per device,
kind and remote, re-counted rather than repeated for a day. Mark one *normal*
and it is never raised again. Beaconing and DGA findings also add "behaviour"
evidence to the remote's score, so the details panel explains it.
"""

from __future__ import annotations

import json
import math
import statistics
import time
from collections import Counter
from dataclasses import dataclass, field
from typing import Any

from .model import Evidence, Indicator, Verdict

RISKY_PORTS = {
    21: "FTP",
    22: "SSH",
    23: "Telnet",
    135: "RPC",
    139: "NetBIOS",
    445: "SMB",
    1080: "SOCKS proxy",
    1433: "MS SQL",
    3306: "MySQL",
    3333: "crypto-mining pool",
    3389: "Remote Desktop",
    4444: "Metasploit / C2",
    5555: "Android debug",
    5900: "VNC",
    6667: "IRC (botnets)",
    9001: "Tor",
    9050: "Tor",
    14444: "crypto-mining pool",
}
SECOND_LEVEL = {
    "co.uk",
    "org.uk",
    "ac.uk",
    "gov.uk",
    "me.uk",
    "com.au",
    "net.au",
    "co.nz",
    "co.jp",
    "com.br",
    "co.in",
    "com.cn",
    "com.tr",
    "co.za",
    "com.mx",
    "co.kr",
    "com.sg",
    "com.hk",
}
QUIET_PORTS = {53, 123, 5353, 1900}  # DNS, NTP, mDNS, SSDP: periodic by design
SEVERITY_RANK = {"low": 0, "medium": 1, "high": 2}


def site(name: str) -> str:
    """The registrable domain: ``a.b.example.co.uk`` -> ``example.co.uk``."""
    labels = name.lower().strip(".").split(".")
    n = 3 if ".".join(labels[-2:]) in SECOND_LEVEL else 2
    return ".".join(labels[-n:])


def randomness(name: str) -> float:
    """How generated the registrable label of a domain looks, 0 (word-like) to 1 (random)."""
    label = site(name).split(".")[0]
    if len(label) < 10 or "-" in label:
        return 0.0
    counts = Counter(label)
    entropy = -sum(c / len(label) * math.log2(c / len(label)) for c in counts.values())
    vowels = sum(ch in "aeiou" for ch in label) / len(label)
    digits = sum(ch.isdigit() for ch in label)
    run = longest = 0
    for ch in label:  # long consonant runs: "xkqvz" doesn't happen in words
        run = run + 1 if ch.isalpha() and ch not in "aeiou" else 0
        longest = max(longest, run)
    score = 0.0
    score += 0.35 if entropy >= 3.2 else 0.15 if entropy >= 2.9 else 0.0
    score += 0.25 if vowels < 0.2 else 0.1 if vowels < 0.3 else 0.0
    score += 0.2 if digits >= 2 and not label.isdigit() else 0.0
    score += 0.2 if longest >= 5 else 0.1 if longest >= 4 else 0.0
    return min(1.0, score)


def beacon(times: list[float], now: float) -> dict[str, float] | None:
    """Regular check-ins: >= 6 connection starts over >= 3 periods with steady intervals."""
    ts = sorted({round(t) for t in times if t >= now - 3600})  # scans see starts in batches: collapse
    if len(ts) < 6:
        return None
    gaps = [b - a for a, b in zip(ts, ts[1:], strict=False)]
    period = statistics.median(gaps)
    if not 2 <= period <= 3600 or ts[-1] - ts[0] < 3 * period:
        return None
    mean = statistics.fmean(gaps)
    cv = statistics.pstdev(gaps) / mean if mean else 1.0
    if cv > 0.25:
        return None
    return {"period": period, "count": len(ts), "jitter": cv}


@dataclass
class Profile:
    who: str
    built: float
    first_seen: float | None
    learning: bool
    remotes: set[str] = field(default_factory=set)
    sites: set[str] = field(default_factory=set)
    ports: set[tuple[str, int, bool]] = field(default_factory=set)
    inbound: bool = False
    hours: list[float] = field(default_factory=lambda: [0.0] * 24)  # share of days active, per hour of day
    hourly_p95: float = 0.0
    days: float = 0.0

    @property
    def narrow(self) -> bool:
        """A device with few habits (plug, camera, printer, TV): anything new matters."""
        return len(self.sites) <= 15 and len(self.remotes) <= 40

    def summary(self) -> dict[str, Any]:
        return {
            "who": self.who,
            "learning": self.learning,
            "days": round(self.days, 1),
            "first_seen": self.first_seen,
            "narrow": self.narrow,
            "remotes": len(self.remotes),
            "sites": len(self.sites),
            "ports": sorted(f"{p}/{proto}{' in' if inbound else ''}" for proto, p, inbound in self.ports)[
                :40
            ],
            "inbound": self.inbound,
            "hours": [round(h, 2) for h in self.hours],
            "hourly_p95": round(self.hourly_p95),
        }


@dataclass
class Finding:
    who: str
    kind: str
    severity: str
    remote: str
    detail: str
    context: dict[str, Any] = field(default_factory=dict)
    evidence: tuple[str, float] | None = None  # (indicator key, confidence) for the remote's score


class Behaviour:
    PROFILE_TTL = 600.0  # rebuild a device's baseline every 10 minutes
    REPEAT_AFTER = 86400.0

    def __init__(self, engine: Any) -> None:
        self.engine = engine
        self.profiles: dict[str, Profile] = {}
        self._hour_flagged: set[tuple[str, int, str]] = set()  # (who, hour, kind) already checked this hour

    @property
    def cfg(self) -> Any:
        return self.engine.config

    # -- baselines ---------------------------------------------------------------------------

    def profile(self, who: str, now: float | None = None) -> Profile:
        now = time.time() if now is None else now
        p = self.profiles.get(who)
        if p is not None and now - p.built < self.PROFILE_TTL:
            return p
        store = self.engine.store
        learn = float(self.cfg.behaviour_learn_days) * 86400
        base = store.baseline(who, now - 60)  # everything seen before this minute
        first = base["first_seen"]
        days = (now - first) / 86400 if first else 0.0
        p = Profile(
            who=who,
            built=now,
            first_seen=first,
            learning=first is None or now - first < learn,
            remotes=base["remotes"],
            sites={site(d) for d in base["domains"]},
            ports=base["ports"],
            inbound=base["inbound"],
            days=days,
        )
        this_hour = int(now // 3600)
        rows = [
            r for r in store.activity(who, this_hour - int(max(learn, 86400) // 3600)) if r[0] < this_hour
        ]
        if rows:
            active_days: dict[int, set[int]] = {h: set() for h in range(24)}
            for hour, flows, lookups in rows:
                if flows or lookups:
                    t = time.localtime(hour * 3600)
                    active_days[t.tm_hour].add(t.tm_yday)
            span_days = max(1.0, (rows[-1][0] - rows[0][0]) / 24)
            p.hours = [min(1.0, len(active_days[h]) / span_days) for h in range(24)]
            flows = sorted(r[1] for r in rows if r[1])
            if flows:
                p.hourly_p95 = flows[min(len(flows) - 1, int(len(flows) * 0.95))]
        self.profiles[who] = p
        return p

    # -- each scan -----------------------------------------------------------------------------

    def observe(
        self,
        conns: list[tuple[float, str, str, int, str, bool, str, int]],
        lookups: list[tuple[float, str, str]],
        starts: dict[tuple, list[float]],
        now: float,
        dns: dict[str, list[str]] | None = None,
    ) -> list[dict[str, Any]]:
        """Count this scan's activity, run the detectors, store and return the new anomalies."""
        hour = int(now // 3600)
        flows: Counter[str] = Counter()
        looks: Counter[str] = Counter()
        for _, who, *_rest, hits in conns:
            flows[who] += hits
        for _, who, _domain in lookups:
            looks[who] += 1
        store = self.engine.store
        store.add_activity((who, hour, flows[who], looks[who]) for who in set(flows) | set(looks))

        findings: list[Finding] = []
        findings += self._beacons(starts, now, dns or {})
        findings += self._dga(lookups)
        for who in set(flows) | set(looks):
            p = self.profile(who, now)
            if p.learning:
                continue
            findings += self._against_baseline(
                p,
                [c for c in conns if c[1] == who],
                [x for x in lookups if x[1] == who],
                hour,
                now,
                # generated-looking names are reported as such, not again as "new"
                {f.remote.split(":", 1)[1] for f in findings if f.who == who and f.kind == "dga"},
            )
        return self._record(findings, now)

    # -- detectors -----------------------------------------------------------------------------

    def _common(self, names: list[str]) -> str | None:
        common = self.engine.common()
        return next((label for n in names if n and (label := common.domain(n))), None)

    def _names(self, ip: str) -> list[str]:
        return [
            e["src"].split(":", 1)[1]
            for e in self.engine.store.edges_of(f"ip:{ip}")
            if e["rel"] == "resolves_to" and e["dst"] == f"ip:{ip}"
        ][:5]

    def _verdict(self, key: str) -> str | None:
        node = self.engine.store.node(key)
        return node["verdict"] if node else None

    def _beacons(
        self, starts: dict[tuple, list[float]], now: float, dns: dict[str, list[str]]
    ) -> list[Finding]:
        out = []
        for (device, proto, remote, port, inbound), times in starts.items():
            if inbound or port in QUIET_PORTS:
                continue
            b = beacon(times, now)
            if b is None:
                continue
            names = dns.get(remote) or self._names(remote)  # this scan's DNS answers, else the graph
            if self._common(names) or self._verdict(f"ip:{remote}") == "benign":
                continue
            label = f"{remote}:{port}" + (f" ({names[0]})" if names else "")
            out.append(
                Finding(
                    f"host:{device}",
                    "beaconing",
                    "high",
                    f"ip:{remote}",
                    f"Checks in with {label} every {b['period']:.0f} s ({b['count']} connections in the last hour, "
                    f"{b['jitter'] * 100:.0f}% jitter). Regular check-ins to one server are how malware talks to its controller.",
                    {
                        "period": b["period"],
                        "count": b["count"],
                        "jitter": round(b["jitter"], 3),
                        "port": port,
                        "proto": proto,
                    },
                    (f"ip:{remote}", 1.0),
                )
            )
        return out

    def _dga(self, lookups: list[tuple[float, str, str]]) -> list[Finding]:
        out = []
        per_device: Counter[str] = Counter()
        for _, who, domain in lookups:
            score = randomness(domain)
            if score < 0.7 or self._common([domain]) or self._verdict(f"domain:{domain}") == "benign":
                continue
            per_device[who] += 1
            out.append(
                Finding(
                    who,
                    "dga",
                    "medium",
                    f"domain:{domain}",
                    f"Looked up {domain}, which looks machine-generated (randomness {score:.2f}). Malware generates "
                    "domain names like this to find its controller.",
                    {"randomness": round(score, 2)},
                    (f"domain:{domain}", 0.8),
                )
            )
        for f in out:  # several at once is a much stronger sign
            if per_device[f.who] >= 3:
                f.severity = "high"
                f.detail += f" {per_device[f.who]} such lookups in this scan."
        return out

    def _against_baseline(
        self,
        p: Profile,
        conns: list[tuple],
        lookups: list[tuple],
        hour: int,
        now: float,
        skip: set[str] = frozenset(),
    ) -> list[Finding]:
        out: list[Finding] = []
        new_destinations: list[tuple[str | None, list[str]]] = []
        covered: set[str] = set(skip)  # names already reported by another finding
        for _, who, ip, port, proto, inbound, names_csv, _hits in conns:
            names = [n for n in names_csv.split(",") if n]
            common = self._common(names)
            if inbound and not common:
                if (proto, port, True) not in p.ports:
                    risky = RISKY_PORTS.get(port)
                    out.append(
                        Finding(
                            who,
                            "new_inbound",
                            "high" if risky else "medium",
                            f"port:{port}/{proto}",
                            f"{ip} connected in on port {port}/{proto}"
                            + (f" ({risky})" if risky else "")
                            + (
                                ". Nothing ever connected in to this device before."
                                if not p.inbound
                                else ". This port never received connections before."
                            ),
                            {"remote": ip, "port": port, "proto": proto},
                        )
                    )
                continue
            if common:
                continue
            new_dest = ip not in p.remotes and not any(site(n) in p.sites for n in names)
            if (proto, port, False) not in p.ports:
                risky = RISKY_PORTS.get(port)
                out.append(
                    Finding(
                        who,
                        "new_port",
                        "high" if risky else "medium",
                        f"port:{port}/{proto}",
                        f"First use of port {port}/{proto}"
                        + (f" ({risky})" if risky else "")
                        + f", to {ip}"
                        + (f" ({names[0]})" if names else "")
                        + (", a server it never contacted before." if new_dest else "."),
                        {
                            "remote": ip,
                            "port": port,
                            "proto": proto,
                            "names": names,
                            "new_destination": new_dest,
                        },
                        (f"ip:{ip}", 0.35) if risky else None,
                    )
                )
                if new_dest:  # one finding for both, and its name is already covered
                    covered.update(names)
                    continue
            if new_dest:
                new_destinations.append((ip, names))
        for _, _who, domain in lookups:
            if site(domain) not in p.sites and not self._common([domain]):
                new_destinations.append((None, [domain]))
        if p.narrow:
            seen: set[str] = set()
            for ip, names in new_destinations:
                # a lookup and the connection to its address are one destination: report the name
                remote = f"domain:{names[0]}" if names else f"ip:{ip}"
                if remote in seen or (names and names[0] in covered):
                    continue
                seen.add(remote)
                what = (names[0] + (f" ({ip})" if ip else "")) if names else str(ip)
                out.append(
                    Finding(
                        p.who,
                        "new_destination",
                        "medium",
                        remote,
                        f"Contacted {what} for the first time. This device normally talks to "
                        f"{len(p.sites) or len(p.remotes)} known place(s).",
                        {"names": names},
                    )
                )
        # hour-level checks, once per device per hour
        activity = self.engine.store.activity(p.who, hour)
        flows_now = activity[0][1] if activity else 0
        if len(new_destinations) and (p.who, hour, "burst") not in self._hour_flagged:
            fresh = len({x[0] or x[1][0] for x in new_destinations})
            if fresh >= max(20, 3 * len(p.sites) // 10):
                self._hour_flagged.add((p.who, hour, "burst"))
                out.append(
                    Finding(
                        p.who,
                        "destination_burst",
                        "medium",
                        f"hour:{hour}",
                        f"{fresh} never-seen destinations in one scan.",
                        {"count": fresh},
                    )
                )
        local_hour = time.localtime(now).tm_hour
        if (
            p.days >= float(self.cfg.behaviour_learn_days)
            and p.hours[local_hour] == 0
            and flows_now >= 5
            and (p.who, hour, "odd") not in self._hour_flagged
        ):
            self._hour_flagged.add((p.who, hour, "odd"))
            out.append(
                Finding(
                    p.who,
                    "odd_hour",
                    "medium" if p.narrow else "low",
                    f"hour:{local_hour}",
                    f"Active at {local_hour:02d}:00, an hour it has been quiet every day for "
                    f"{p.days:.0f} days ({flows_now} connections so far).",
                    {"hour": local_hour},
                )
            )
        if (
            p.hourly_p95
            and flows_now >= 200
            and flows_now > max(3 * p.hourly_p95, p.hourly_p95 + 100)
            and (p.who, hour, "volume") not in self._hour_flagged
        ):
            self._hour_flagged.add((p.who, hour, "volume"))
            out.append(
                Finding(
                    p.who,
                    "volume_spike",
                    "medium",
                    f"hour:{hour}",
                    f"{flows_now} connections this hour; a busy hour is usually about {p.hourly_p95:.0f}.",
                    {"flows": flows_now, "p95": p.hourly_p95},
                )
            )
        if len(self._hour_flagged) > 10_000:
            self._hour_flagged = {x for x in self._hour_flagged if x[1] >= hour - 1}
        return out

    # -- storing ---------------------------------------------------------------------------------

    def _record(self, findings: list[Finding], now: float) -> list[dict[str, Any]]:
        store, new, rescore = self.engine.store, [], set()
        for f in findings:
            res = store.record_anomaly(
                f.who,
                f.kind,
                f.remote,
                f.severity,
                f.detail[:1000],
                json.dumps(f.context, default=str),
                now,
                self.REPEAT_AFTER,
            )
            if res is None:  # marked normal
                continue
            anomaly_id, is_new = res
            if f.evidence and is_new:
                key, confidence = f.evidence
                ind = Indicator.from_key(key)
                store.upsert_node(ind)
                kept = [e for e in store.evidence(key) if e.source == "behaviour" and e.detail != f.detail]
                store.replace_evidence(
                    key,
                    "behaviour",
                    [*kept, Evidence("behaviour", Verdict.SUSPICIOUS, f.detail[:300], confidence)],
                )
                rescore.add(key)
            if is_new:
                new.append(store.anomaly(anomaly_id))
        if rescore:
            self.engine.rescore(rescore)
        return [a for a in new if a]

    # -- reading -------------------------------------------------------------------------------

    def status(self, now: float | None = None) -> dict[str, Any]:
        now = time.time() if now is None else now
        whos = self.engine.store.log_whos()
        profiles = [self.profile(w, now) for w in whos[:500]]
        recent = self.engine.store.anomalies(since=now - 86400, limit=1000)
        open_ = [a for a in recent if a["status"] == "open"]
        return {
            "enabled": bool(self.cfg.behaviour),
            "learn_days": self.cfg.behaviour_learn_days,
            "devices": len(profiles),
            "learning": sum(p.learning for p in profiles),
            "anomalies_24h": len(recent),
            "open": len(open_),
            "high": sum(a["severity"] == "high" for a in open_),
        }


def describe(kind: str) -> str:
    return {
        "beaconing": "Regular check-ins",
        "dga": "Generated-looking domain",
        "new_inbound": "New inbound connection",
        "new_port": "New port",
        "new_destination": "New destination",
        "destination_burst": "Burst of new destinations",
        "odd_hour": "Unusual hour",
        "volume_spike": "Traffic spike",
    }.get(kind, kind)
